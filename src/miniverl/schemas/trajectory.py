"""Trajectory schema with strict token provenance.

A :class:`Trajectory` is a *flat token sequence* plus a partition of that
sequence into typed :class:`Span` objects.  Every token belongs to exactly one
span, and the span type is what decides whether the token may ever contribute
to a training loss.

Provenance rules (enforced by validators, not by convention)
------------------------------------------------------------
* ``system`` / ``user`` / ``tool_result`` tokens are **context**.  They are
  never targets.
* ``assistant_text`` / ``assistant_tool_call`` / ``assistant_final`` tokens were
  produced by the policy being trained.  Only these may be targets.
* ``assistant_tool_call`` and ``assistant_final`` are additionally *critical*:
  they are the structurally load-bearing tokens (the tool JSON and the answer).

The three masks are stored explicitly rather than recomputed on read, and the
validator re-derives them from the spans and rejects any mismatch.  A tampered
or hand-edited file therefore fails loudly instead of silently training on tool
output.
"""

from __future__ import annotations

from enum import Enum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, model_validator

__all__ = [
    "SpanType",
    "TerminationReason",
    "Span",
    "Turn",
    "ToolCallRecord",
    "ToolResultRecord",
    "VerificationRecord",
    "Trajectory",
    "MODEL_GENERATED_SPAN_TYPES",
    "CRITICAL_SPAN_TYPES",
    "TRAJECTORY_SCHEMA_VERSION",
]

TRAJECTORY_SCHEMA_VERSION = 1


class SpanType(str, Enum):
    """Provenance of a contiguous run of tokens."""

    SYSTEM = "system"
    USER = "user"
    ASSISTANT_TEXT = "assistant_text"
    ASSISTANT_TOOL_CALL = "assistant_tool_call"
    TOOL_RESULT = "tool_result"
    ASSISTANT_FINAL = "assistant_final"


#: Span types whose tokens were generated by the policy under training.
MODEL_GENERATED_SPAN_TYPES: frozenset[SpanType] = frozenset(
    {
        SpanType.ASSISTANT_TEXT,
        SpanType.ASSISTANT_TOOL_CALL,
        SpanType.ASSISTANT_FINAL,
    }
)

#: Structurally load-bearing model spans (tool-call payloads and final answers).
CRITICAL_SPAN_TYPES: frozenset[SpanType] = frozenset(
    {
        SpanType.ASSISTANT_TOOL_CALL,
        SpanType.ASSISTANT_FINAL,
    }
)


class TerminationReason(str, Enum):
    """Why a rollout stopped.  Every trajectory records exactly one."""

    FINAL_ANSWER = "final_answer"
    MAX_TURNS = "max_turns"
    MAX_TOKENS = "max_tokens"
    PARSE_ERROR_LIMIT = "parse_error_limit"
    REPEATED_CALL_LIMIT = "repeated_call_limit"
    ENVIRONMENT_ERROR = "environment_error"
    EOS_WITHOUT_FINAL = "eos_without_final"


class Span(BaseModel):
    """A half-open token range ``[start, end)`` with a single provenance type."""

    model_config = ConfigDict(extra="forbid")

    span_type: SpanType
    start: int = Field(ge=0)
    end: int = Field(ge=0)
    turn_id: int = Field(ge=0)
    text: str = ""
    tool_name: str | None = None
    tool_call_id: str | None = None
    env_state_id: str | None = None
    metadata: dict[str, Any] = Field(default_factory=dict)

    @model_validator(mode="after")
    def _check_range(self) -> Span:
        if self.end <= self.start:
            raise ValueError(f"span {self.span_type.value} has empty range [{self.start},{self.end})")
        return self

    @property
    def length(self) -> int:
        """Number of tokens in the span."""
        return self.end - self.start

    @property
    def is_model_generated(self) -> bool:
        """``True`` when the policy produced these tokens."""
        return self.span_type in MODEL_GENERATED_SPAN_TYPES

    @property
    def is_critical(self) -> bool:
        """``True`` for tool-call payloads and final answers."""
        return self.span_type in CRITICAL_SPAN_TYPES


class ToolCallRecord(BaseModel):
    """A parsed tool call emitted by the policy."""

    model_config = ConfigDict(extra="forbid")

    call_id: str
    name: str
    arguments: dict[str, Any] = Field(default_factory=dict)
    raw_text: str = ""
    valid: bool = True
    parse_error: str | None = None


class ToolResultRecord(BaseModel):
    """The environment's response to a tool call."""

    model_config = ConfigDict(extra="forbid")

    call_id: str
    ok: bool
    result: str = ""
    error: str | None = None
    env_state_id: str | None = None
    duration_ms: float | None = None


class VerificationRecord(BaseModel):
    """Outcome of the environment's exact verifier for a finished rollout."""

    model_config = ConfigDict(extra="forbid")

    solved: bool
    reward: float = 0.0
    predicted: str | None = None
    expected: str | None = None
    failure_category: str | None = None
    detail: str | None = None


class Turn(BaseModel):
    """One assistant action and the environment response it triggered."""

    model_config = ConfigDict(extra="forbid")

    turn_id: int = Field(ge=0)
    tool_call: ToolCallRecord | None = None
    tool_result: ToolResultRecord | None = None
    is_final: bool = False


class Trajectory(BaseModel):
    """A tokenized multi-turn rollout with explicit per-token provenance."""

    model_config = ConfigDict(extra="forbid")

    schema_version: int = TRAJECTORY_SCHEMA_VERSION
    trajectory_id: str
    task_id: str
    environment: str

    token_ids: list[int]
    attention_mask: list[int]
    model_generated_mask: list[bool]
    critical_mask: list[bool]
    spans: list[Span]
    turns: list[Turn] = Field(default_factory=list)

    policy_version: int = Field(ge=0, default=0)
    tokenizer_fingerprint: str
    model_id: str
    model_revision: str | None = None

    verification: VerificationRecord | None = None
    termination_reason: TerminationReason
    generated_token_count: int = Field(ge=0, default=0)
    invalid_tool_calls: int = Field(ge=0, default=0)
    metadata: dict[str, Any] = Field(default_factory=dict)

    # -- validation ----------------------------------------------------

    @model_validator(mode="after")
    def _validate_structure(self) -> Trajectory:
        n = len(self.token_ids)
        if n == 0:
            raise ValueError("trajectory has no tokens")
        for field_name, seq in (
            ("attention_mask", self.attention_mask),
            ("model_generated_mask", self.model_generated_mask),
            ("critical_mask", self.critical_mask),
        ):
            if len(seq) != n:
                raise ValueError(
                    f"{field_name} has length {len(seq)} but token_ids has length {n}"
                )
        if any(v not in (0, 1) for v in self.attention_mask):
            raise ValueError("attention_mask must contain only 0/1")

        if not self.spans:
            raise ValueError("trajectory has no spans")
        ordered = sorted(self.spans, key=lambda s: s.start)
        if [s.start for s in ordered] != [s.start for s in self.spans]:
            raise ValueError("spans must be stored in ascending start order")

        cursor = 0
        for span in self.spans:
            if span.start != cursor:
                raise ValueError(
                    f"spans must tile the sequence without gaps or overlaps: "
                    f"expected next span to start at {cursor}, got {span.start}"
                )
            cursor = span.end
        if cursor != n:
            raise ValueError(f"spans cover {cursor} tokens but the sequence has {n}")

        expected_model = [False] * n
        expected_critical = [False] * n
        for span in self.spans:
            if span.is_model_generated:
                for i in range(span.start, span.end):
                    expected_model[i] = True
            if span.is_critical:
                for i in range(span.start, span.end):
                    expected_critical[i] = True

        if list(self.model_generated_mask) != expected_model:
            raise ValueError(
                "model_generated_mask disagrees with the span partition; "
                "tool/user/system tokens must never be marked model-generated"
            )
        if list(self.critical_mask) != expected_critical:
            raise ValueError("critical_mask disagrees with the span partition")

        turn_ids = {t.turn_id for t in self.turns}
        for span in self.spans:
            if span.turn_id not in turn_ids and self.turns:
                raise ValueError(
                    f"span {span.span_type.value} references unknown turn_id {span.turn_id}"
                )
        return self

    # -- derived views -------------------------------------------------

    @property
    def length(self) -> int:
        """Total number of tokens."""
        return len(self.token_ids)

    def model_token_positions(self) -> list[int]:
        """Absolute indices of tokens generated by the policy."""
        return [i for i, flag in enumerate(self.model_generated_mask) if flag]

    def critical_token_positions(self) -> list[int]:
        """Absolute indices of tool-call/final-answer tokens."""
        return [i for i, flag in enumerate(self.critical_mask) if flag]

    def spans_of(self, *span_types: SpanType) -> list[Span]:
        """All spans whose type is in ``span_types``."""
        wanted = set(span_types)
        return [s for s in self.spans if s.span_type in wanted]

    def span_at(self, position: int) -> Span:
        """Return the span containing absolute token ``position``."""
        for span in self.spans:
            if span.start <= position < span.end:
                return span
        raise IndexError(f"position {position} is outside the trajectory")

    def token_counts_by_span_type(self) -> dict[str, int]:
        """Token totals keyed by span type value."""
        counts: dict[str, int] = {}
        for span in self.spans:
            counts[span.span_type.value] = counts.get(span.span_type.value, 0) + span.length
        return counts
