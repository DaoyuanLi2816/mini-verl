"""Trajectory schema with strict token provenance.

A :class:`Trajectory` is a *flat token sequence* plus a partition of that
sequence into typed :class:`Span` objects.  Every token belongs to exactly one
span, and the span type is what decides whether the token may ever contribute
to a training loss.

Provenance rules (enforced by validators, not by convention)
------------------------------------------------------------
* ``system`` / ``user`` / ``tool_result`` tokens are **context**.  They are
  never targets.
* ``assistant_text`` / ``assistant_tool_call`` / ``assistant_final`` tokens were
  produced by the policy being trained.  Only these may be targets.
* ``assistant_tool_call`` and ``assistant_final`` are additionally *critical*:
  they are the structurally load-bearing tokens (the tool JSON and the answer).

The three masks are stored explicitly rather than recomputed on read, and the
validator re-derives them from the spans and rejects any mismatch.  A tampered
or hand-edited file therefore fails loudly instead of silently training on tool
output.
"""

from __future__ import annotations

import hashlib
from enum import Enum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, model_validator

__all__ = [
    "SpanType",
    "TerminationReason",
    "Span",
    "Turn",
    "ToolCallRecord",
    "ToolResultRecord",
    "VerificationRecord",
    "Trajectory",
    "MODEL_GENERATED_SPAN_TYPES",
    "CRITICAL_SPAN_TYPES",
    "TRAJECTORY_SCHEMA_VERSION",
    "derive_grouped_trajectory_id",
    "validate_trajectory_groups",
]

LEGACY_TRAJECTORY_SCHEMA_VERSION = 1
PRE_GROUP_TRAJECTORY_SCHEMA_VERSION = 2
TRAJECTORY_SCHEMA_VERSION = 3
READABLE_TRAJECTORY_SCHEMA_VERSIONS = frozenset(
    {
        LEGACY_TRAJECTORY_SCHEMA_VERSION,
        PRE_GROUP_TRAJECTORY_SCHEMA_VERSION,
        TRAJECTORY_SCHEMA_VERSION,
    }
)


def derive_grouped_trajectory_id(
    *,
    prompt_group_id: str,
    sample_index: int,
    rollout_policy_identity_digest: str,
    generation_seed: int,
) -> str:
    """Bind one trajectory ID to its logical group, sample, policy and seed."""

    payload = (
        f"miniverl-trajectory-v3\0{prompt_group_id}\0{sample_index}\0"
        f"{rollout_policy_identity_digest}\0{generation_seed}"
    ).encode()
    return hashlib.sha256(payload).hexdigest()


def _is_sha256(value: str | None) -> bool:
    return bool(
        value and len(value) == 64 and all(character in "0123456789abcdef" for character in value)
    )


class SpanType(str, Enum):
    """Provenance of a contiguous run of tokens."""

    SYSTEM = "system"
    USER = "user"
    ASSISTANT_TEXT = "assistant_text"
    ASSISTANT_TOOL_CALL = "assistant_tool_call"
    TOOL_RESULT = "tool_result"
    ASSISTANT_FINAL = "assistant_final"


#: Span types whose tokens were generated by the policy under training.
MODEL_GENERATED_SPAN_TYPES: frozenset[SpanType] = frozenset(
    {
        SpanType.ASSISTANT_TEXT,
        SpanType.ASSISTANT_TOOL_CALL,
        SpanType.ASSISTANT_FINAL,
    }
)

#: Structurally load-bearing model spans (tool-call payloads and final answers).
CRITICAL_SPAN_TYPES: frozenset[SpanType] = frozenset(
    {
        SpanType.ASSISTANT_TOOL_CALL,
        SpanType.ASSISTANT_FINAL,
    }
)


class TerminationReason(str, Enum):
    """Why a rollout stopped.  Every trajectory records exactly one."""

    FINAL_ANSWER = "final_answer"
    MAX_TURNS = "max_turns"
    MAX_TOKENS = "max_tokens"
    PARSE_ERROR_LIMIT = "parse_error_limit"
    REPEATED_CALL_LIMIT = "repeated_call_limit"
    ENVIRONMENT_ERROR = "environment_error"
    EOS_WITHOUT_FINAL = "eos_without_final"


class Span(BaseModel):
    """A half-open token range ``[start, end)`` with a single provenance type."""

    model_config = ConfigDict(extra="forbid")

    span_type: SpanType
    start: int = Field(ge=0)
    end: int = Field(ge=0)
    turn_id: int = Field(ge=0)
    text: str = ""
    tool_name: str | None = None
    tool_call_id: str | None = None
    env_state_id: str | None = None
    metadata: dict[str, Any] = Field(default_factory=dict)

    @model_validator(mode="after")
    def _check_range(self) -> Span:
        if self.end <= self.start:
            raise ValueError(
                f"span {self.span_type.value} has empty range [{self.start},{self.end})"
            )
        return self

    @property
    def length(self) -> int:
        """Number of tokens in the span."""
        return self.end - self.start

    @property
    def is_model_generated(self) -> bool:
        """``True`` when the policy produced these tokens."""
        return self.span_type in MODEL_GENERATED_SPAN_TYPES

    @property
    def is_critical(self) -> bool:
        """``True`` for tool-call payloads and final answers."""
        return self.span_type in CRITICAL_SPAN_TYPES


class ToolCallRecord(BaseModel):
    """A parsed tool call emitted by the policy."""

    model_config = ConfigDict(extra="forbid")

    call_id: str
    name: str
    arguments: dict[str, Any] = Field(default_factory=dict)
    raw_text: str = ""
    valid: bool = True
    parse_error: str | None = None


class ToolResultRecord(BaseModel):
    """The environment's response to a tool call."""

    model_config = ConfigDict(extra="forbid")

    call_id: str
    ok: bool
    result: str = ""
    error: str | None = None
    env_state_id: str | None = None
    duration_ms: float | None = None
    error_code: str | None = None
    retryable: bool | None = None
    intervention: bool = False
    tool_result_metadata: dict[str, Any] = Field(default_factory=dict)


class VerificationRecord(BaseModel):
    """Outcome of the environment's exact verifier for a finished rollout."""

    model_config = ConfigDict(extra="forbid")

    solved: bool
    reward: float = 0.0
    predicted: str | None = None
    expected: str | None = None
    failure_category: str | None = None
    detail: str | None = None


class Turn(BaseModel):
    """One assistant action and the environment response it triggered."""

    model_config = ConfigDict(extra="forbid")

    turn_id: int = Field(ge=0)
    tool_call: ToolCallRecord | None = None
    tool_result: ToolResultRecord | None = None
    is_final: bool = False


class Trajectory(BaseModel):
    """A tokenized multi-turn rollout with explicit per-token provenance."""

    model_config = ConfigDict(extra="forbid")

    # Keep direct construction backward compatible for downstream callers.
    # Runtime writers explicitly upgrade new artifacts to the current schema.
    schema_version: int = PRE_GROUP_TRAJECTORY_SCHEMA_VERSION
    trajectory_id: str
    task_id: str
    environment: str

    token_ids: list[int]
    attention_mask: list[int]
    model_generated_mask: list[bool]
    critical_mask: list[bool]
    spans: list[Span]
    turns: list[Turn] = Field(default_factory=list)

    policy_version: int = Field(ge=0, default=0)
    tokenizer_fingerprint: str
    model_id: str
    model_revision: str | None = None

    # Schema-v3 rollout identity. Versions 1 and 2 remain readable with these
    # fields absent; every new grouped-rollout writer emits version 3.
    prompt_group_id: str | None = None
    prompt_digest: str | None = None
    sample_index: int | None = Field(default=None, ge=0)
    samples_per_prompt: int | None = Field(default=None, ge=1)
    generation_seed: int | None = Field(default=None, ge=0)
    rollout_backend: str | None = None
    rollout_policy_identity_digest: str | None = None

    verification: VerificationRecord | None = None
    termination_reason: TerminationReason
    generated_token_count: int = Field(ge=0, default=0)
    invalid_tool_calls: int = Field(ge=0, default=0)
    assistant_turns: int | None = Field(default=None, ge=0)
    emitted_tool_calls: int | None = Field(default=None, ge=0)
    parsed_tool_calls: int | None = Field(default=None, ge=0)
    tool_execution_successes: int | None = Field(default=None, ge=0)
    tool_execution_errors: int | None = Field(default=None, ge=0)
    unknown_tool_calls: int | None = Field(default=None, ge=0)
    parse_errors: int | None = Field(default=None, ge=0)
    repeated_call_terminations: int | None = Field(default=None, ge=0)
    final_answers_emitted: int | None = Field(default=None, ge=0)
    final_answers_format_valid: int | None = Field(default=None, ge=0)
    final_answers_verified: int | None = Field(default=None, ge=0)
    metadata: dict[str, Any] = Field(default_factory=dict)

    # -- validation ----------------------------------------------------

    @model_validator(mode="after")
    def _validate_structure(self) -> Trajectory:
        if self.schema_version not in READABLE_TRAJECTORY_SCHEMA_VERSIONS:
            raise ValueError(f"trajectory schema_version {self.schema_version!r} is not readable")
        grouped = (
            self.prompt_group_id,
            self.prompt_digest,
            self.sample_index,
            self.samples_per_prompt,
            self.generation_seed,
            self.rollout_backend,
            self.rollout_policy_identity_digest,
        )
        if self.schema_version >= TRAJECTORY_SCHEMA_VERSION:
            if any(value is None or value == "" for value in grouped):
                raise ValueError("trajectory schema v3 requires complete grouped rollout identity")
            assert self.sample_index is not None
            assert self.samples_per_prompt is not None
            if self.sample_index >= self.samples_per_prompt:
                raise ValueError("sample_index must be smaller than samples_per_prompt")
            if not _is_sha256(self.prompt_digest):
                raise ValueError("prompt_digest must be a lowercase SHA-256 digest")
            if not _is_sha256(self.rollout_policy_identity_digest):
                raise ValueError(
                    "rollout_policy_identity_digest must be a lowercase SHA-256 digest"
                )
            assert self.prompt_group_id is not None
            assert self.generation_seed is not None
            assert self.rollout_policy_identity_digest is not None
            expected_id = derive_grouped_trajectory_id(
                prompt_group_id=self.prompt_group_id,
                sample_index=self.sample_index,
                rollout_policy_identity_digest=self.rollout_policy_identity_digest,
                generation_seed=self.generation_seed,
            )
            if self.trajectory_id != expected_id:
                raise ValueError(
                    "trajectory_id must bind prompt group, sample, policy identity and seed"
                )
        elif any(value is not None for value in grouped):
            raise ValueError("legacy trajectory schemas cannot contain schema-v3 grouped fields")

        n = len(self.token_ids)
        if n == 0:
            raise ValueError("trajectory has no tokens")
        for field_name, seq in (
            ("attention_mask", self.attention_mask),
            ("model_generated_mask", self.model_generated_mask),
            ("critical_mask", self.critical_mask),
        ):
            if len(seq) != n:
                raise ValueError(f"{field_name} has length {len(seq)} but token_ids has length {n}")
        if any(v not in (0, 1) for v in self.attention_mask):
            raise ValueError("attention_mask must contain only 0/1")

        if not self.spans:
            raise ValueError("trajectory has no spans")
        ordered = sorted(self.spans, key=lambda s: s.start)
        if [s.start for s in ordered] != [s.start for s in self.spans]:
            raise ValueError("spans must be stored in ascending start order")

        cursor = 0
        for span in self.spans:
            if span.start != cursor:
                raise ValueError(
                    f"spans must tile the sequence without gaps or overlaps: "
                    f"expected next span to start at {cursor}, got {span.start}"
                )
            cursor = span.end
        if cursor != n:
            raise ValueError(f"spans cover {cursor} tokens but the sequence has {n}")

        expected_model = [False] * n
        expected_critical = [False] * n
        for span in self.spans:
            if span.is_model_generated:
                for i in range(span.start, span.end):
                    expected_model[i] = True
            if span.is_critical:
                for i in range(span.start, span.end):
                    expected_critical[i] = True

        if list(self.model_generated_mask) != expected_model:
            raise ValueError(
                "model_generated_mask disagrees with the span partition; "
                "tool/user/system tokens must never be marked model-generated"
            )
        if list(self.critical_mask) != expected_critical:
            raise ValueError("critical_mask disagrees with the span partition")

        turn_ids = {t.turn_id for t in self.turns}
        for span in self.spans:
            if span.turn_id not in turn_ids and self.turns:
                raise ValueError(
                    f"span {span.span_type.value} references unknown turn_id {span.turn_id}"
                )
        return self

    # -- derived views -------------------------------------------------

    @property
    def length(self) -> int:
        """Total number of tokens."""
        return len(self.token_ids)

    def model_token_positions(self) -> list[int]:
        """Absolute indices of tokens generated by the policy."""
        return [i for i, flag in enumerate(self.model_generated_mask) if flag]

    def critical_token_positions(self) -> list[int]:
        """Absolute indices of tool-call/final-answer tokens."""
        return [i for i, flag in enumerate(self.critical_mask) if flag]

    def spans_of(self, *span_types: SpanType) -> list[Span]:
        """All spans whose type is in ``span_types``."""
        wanted = set(span_types)
        return [s for s in self.spans if s.span_type in wanted]

    def span_at(self, position: int) -> Span:
        """Return the span containing absolute token ``position``."""
        for span in self.spans:
            if span.start <= position < span.end:
                return span
        raise IndexError(f"position {position} is outside the trajectory")

    def token_counts_by_span_type(self) -> dict[str, int]:
        """Token totals keyed by span type value."""
        counts: dict[str, int] = {}
        for span in self.spans:
            counts[span.span_type.value] = counts.get(span.span_type.value, 0) + span.length
        return counts


def validate_trajectory_groups(trajectories: list[Trajectory]) -> None:
    """Reject incomplete, duplicated or internally inconsistent schema-v3 groups."""

    if not trajectories:
        raise ValueError("trajectory group collection cannot be empty")
    groups: dict[str, list[Trajectory]] = {}
    identities: set[tuple[str, int]] = set()
    for trajectory in trajectories:
        if trajectory.schema_version != TRAJECTORY_SCHEMA_VERSION:
            raise ValueError("grouped rollout publication requires trajectory schema v3")
        assert trajectory.prompt_group_id is not None
        assert trajectory.sample_index is not None
        identity = (trajectory.prompt_group_id, trajectory.sample_index)
        if identity in identities:
            raise ValueError("duplicate (prompt_group_id, sample_index) trajectory")
        identities.add(identity)
        groups.setdefault(trajectory.prompt_group_id, []).append(trajectory)

    for group_id, members in groups.items():
        expected_size = members[0].samples_per_prompt
        prompt_digest = members[0].prompt_digest
        policy_digest = members[0].rollout_policy_identity_digest
        if expected_size is None:
            raise ValueError(f"group {group_id!r} has no samples_per_prompt")
        if len(members) != expected_size:
            raise ValueError(
                f"group {group_id!r} is incomplete: {len(members)} of {expected_size} samples"
            )
        if {member.samples_per_prompt for member in members} != {expected_size}:
            raise ValueError(f"group {group_id!r} mixes samples_per_prompt values")
        if {member.prompt_digest for member in members} != {prompt_digest}:
            raise ValueError(f"group {group_id!r} mixes prompt digests")
        if {member.rollout_policy_identity_digest for member in members} != {policy_digest}:
            raise ValueError(f"group {group_id!r} mixes rollout policy identities")
        if {member.sample_index for member in members} != set(range(expected_size)):
            raise ValueError(f"group {group_id!r} does not contain sample indices 0..n-1")
